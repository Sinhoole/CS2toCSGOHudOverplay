/**
 * 游戏侧配套命令 —— 要在 CS2 控制台里执行的那几条。
 *
 * 背景：覆盖层要好看，前提是先把 CS2 原生 HUD 关掉；但有几样东西 GSI 拿不到
 * （本地玩家的雷达位置、队友头顶标识），必须「关掉 HUD 的同时单独把原生那几个留住」。
 * 这一组命令以前只能用户自己手打，现在集中到这个模块：
 *
 *   1. 生成一份**独立的** cfg（overplayhud_gamesetup.cfg），绝不碰游戏自带的文件；
 *   2. 写进 CS2 的两个 cfg 目录（game/csgo/cfg 与 game/core/cfg），复用 gsi-install 的探测；
 *   3. 可选：在 autoexec.cfg 里维护一段**带标记**的区块，撤销时原样删掉、不动用户其它行。
 *
 * ⚠️ 底线：这里只写文本文件，不模拟按键、不注入进程。cfg 生不生效由游戏自己决定 ——
 *    和「控制台命令关原生 HUD」的分工完全一致，只是把命令替用户抄好了。
 *
 * ⚠️ cfg 正文只用 ASCII 注释：Source 引擎的 cfg 解析器对非 ASCII 编码不保证，
 *    中文说明一律留在设置界面与 TUTORIAL.md 里，别写进 cfg。
 */

const fs = require('fs');
const path = require('path');
const { findGameRoots, targets, isGameRunning } = require('./gsi-install');

/** 生成的 cfg 文件名（放在 CS2 的 cfg 目录里） */
const CFG_NAME = 'overplayhud_gamesetup.cfg';
/** 控制台里执行的短名：exec overplayhud_gamesetup */
const EXEC_NAME = 'overplayhud_gamesetup';
/** 把命令挂进开机自动执行时用的文件 */
const AUTOEXEC = 'autoexec.cfg';
/** 区块标记：靠这两行定位，才能只删自己写的那段 */
const MARK_BEGIN = '// >>>>> OverplayHUD game setup (auto-generated) >>>>>';
const MARK_END = '// <<<<< OverplayHUD game setup <<<<<';

/** 界面上的分组（顺序即显示顺序）。label 给界面看，en 写进 cfg（ASCII）。 */
