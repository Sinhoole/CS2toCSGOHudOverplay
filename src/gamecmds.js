/** 所有命令 id（config.js 用它生成默认开关表） */
const IDS = CATALOG.map((c) => c.id);

function byId(id) {
  return CATALOG.find((c) => c.id === id) || null;
}

/** 全开 */
function defaultEnabled() {
  const out = {};
  for (const id of IDS) out[id] = true;
  return out;
}

/** 把外部传进来的开关表规范成「每一条都有值」；只认显式 false 为关 */
function resolveEnabled(map) {
  const out = {};
  for (const id of IDS) out[id] = !(map && map[id] === false);
  return out;
}

/** 勾选中的条目（按目录顺序） */
function selected(map) {
  const on = resolveEnabled(map);
  return CATALOG.filter((c) => on[c.id]);
}

/** 控制台里执行的那一行 */
function execLine() {
  return 'exec ' + EXEC_NAME;
}

/** 要写进 cfg 的正文（ASCII 注释 + 命令） */
function cfgText(map) {
  const list = selected(map);
  const lines = [
    '// ============================================================',
    '//  OverplayHUD - game side companion commands',
    '//  Generated by the OverplayHUD settings window. Safe to delete.',
    '//',
    '//  How to use:',
    '//    - once per session : run in the CS2 console ->  ' + execLine(),
    '//    - every launch     : tick "write into autoexec.cfg" in the',
    '//                         OverplayHUD settings window.',
    '//',
    '//  Chinese explanations live in the settings window / TUTORIAL.md.',
    '//  This file is kept ASCII on purpose: Source cfg parsing does not',
    '//  guarantee non-ASCII handling.',
    '// ============================================================',
    '',
  ];

  let lastGroup = '';
  for (const c of list) {
    if (c.group !== lastGroup) {
      lastGroup = c.group;
      const g = GROUPS.find((x) => x.id === c.group);
      lines.push('// ---- ' + (g ? g.en : c.group) + ' ----');
    }
    // ⚠️ 注释只写 ASCII：中文说明留在设置界面 / TUTORIAL.md，不往 cfg 里塞
    lines.push('// ' + (c.en || c.id));
    lines.push(c.cmd);
    lines.push('');
  }

  return lines.join('\n').replace(/\n{3,}/g, '\n\n').replace(/\n+$/, '') + '\n';
}

/** 开机自动执行时要塞进 autoexec.cfg 的那一段 */
function blockText(map) {
  return [MARK_BEGIN].concat(selected(map).map((c) => c.cmd), [MARK_END]).join('\n');
}

/**
 * 从文本里摘掉我们的区块。
 * 返回 { text, removed }；removed=false 表示本来就没有我们的块，调用方应原样写回。
 */
function stripBlock(text) {
  const src = String(text == null ? '' : text);
  const i = src.indexOf(MARK_BEGIN);
  if (i < 0) return { text: src, removed: false };
  const eol = src.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  const j = src.indexOf(MARK_END, i);
  const end = j < 0 ? src.length : j + MARK_END.length;

  const head = src.slice(0, i).replace(/(?:(?:\r?\n)[ \t]*)+$/, '');
  const tail = src.slice(end).replace(/^(?:\r?\n)+/, '');
  let out;
  if (!head.trim()) out = tail;
  else if (!tail.trim()) out = head + eol;
  else out = head + eol + eol + tail;
  return { text: out, removed: true };
}

/** 写入 / 替换区块（保留用户 autoexec 里的其它内容） */
function upsertBlock(text, map) {
  const src = String(text == null ? '' : text);
  const eol = src.indexOf('\r\n') >= 0 ? '\r\n' : '\n';
  const { text: base } = stripBlock(src);
  const block = blockText(map).split('\n').join(eol);
  if (!base.trim()) return block + eol;
  return base.replace(/[\s]+$/, '') + eol + eol + block + eol;
}

/** 每个 CS2 安装目录对应的 autoexec.cfg 路径（只认 game/csgo/cfg，那里才是游戏读的） */
function autoexecPaths(manual) {
  return findGameRoots(manual)
    .map((root) => path.join(root, 'game', 'csgo', 'cfg', AUTOEXEC))
    .filter((p) => fs.existsSync(path.dirname(p)));
}

/** 把命令目录写成独立 cfg，写进所有 CS2 cfg 目录 */
function writeCfg(map, manual) {
  const data = cfgText(map);
  const copied = [];
  const failed = [];
  const roots = findGameRoots(manual);

  for (const root of roots) {
    for (const dir of targets(root)) {
      if (!fs.existsSync(dir)) continue;
      const dest = path.join(dir, CFG_NAME);
      try {
        fs.writeFileSync(dest, data, 'utf8');
        copied.push(dest);
      } catch (e) {
        failed.push(dest + ' — ' + e.message);
      }
    }
  }
  return { copied, failed, roots: roots.length };
}

/** 在 autoexec.cfg 里维护我们的区块 */
function writeAutoexec(map, manual) {
  const copied = [];
  const failed = [];
  const paths = autoexecPaths(manual);

  for (const p of paths) {
    try {
      const old = fs.existsSync(p) ? fs.readFileSync(p, 'utf8') : '';
      fs.writeFileSync(p, upsertBlock(old, map), 'utf8');
      copied.push(p);
    } catch (e) {
      failed.push(p + ' — ' + e.message);
    }
  }
  return { copied, failed, roots: paths.length };
}

/**
 * 把区块从 autoexec.cfg 摘掉。
 * ⚠️ 即使摘完文件变成空的也不删文件 —— 我们无法区分「这个 autoexec 是我们建的」
 *    还是「用户本来就有一个（只是空的）」，删错文件的代价比留一个空文件大得多。
 */
function removeAutoexec(manual) {
  const removed = [];
  const failed = [];
  for (const p of autoexecPaths(manual)) {
    try {
      if (!fs.existsSync(p)) continue;
      const old = fs.readFileSync(p, 'utf8');
      const { text, removed: hit } = stripBlock(old);
      if (!hit) continue;
      fs.writeFileSync(p, text, 'utf8');
      removed.push(p);
    } catch (e) {
      failed.push(p + ' — ' + e.message);
    }
  }
  return { removed, failed };
}

/** 删掉生成的 cfg（不碰 autoexec） */
function removeCfg(manual) {
  const removed = [];
  const failed = [];
  for (const root of findGameRoots(manual)) {
    for (const dir of targets(root)) {
      const p = path.join(dir, CFG_NAME);
      try {
        if (fs.existsSync(p)) { fs.unlinkSync(p); removed.push(p); }
      } catch (e) {
        failed.push(p + ' — ' + e.message);
      }
    }
  }
  return { removed, failed };
}

/**
 * 只读检查：CS2 找没找到、cfg 装没装、autoexec 里有没有我们的块。
 * 关闭设置界面时不能靠猜，状态一律现查。
 */
function inspect(manual) {
  const roots = findGameRoots(manual).map((root) => {
    const ax = path.join(root, 'game', 'csgo', 'cfg', AUTOEXEC);
    let hasBlock = false;
    try {
      hasBlock = fs.existsSync(ax) && fs.readFileSync(ax, 'utf8').indexOf(MARK_BEGIN) >= 0;
    } catch (e) { /* 读不了就当没有 */ }
    return {
      path: root,
      autoexec: ax,
      autoexecExists: fs.existsSync(ax),
      autoexecHasBlock: hasBlock,
      dirs: targets(root).map((dir) => ({
        dir,
        exists: fs.existsSync(dir),
        installed: fs.existsSync(path.join(dir, CFG_NAME)),
      })),
    };
  });

  return {
    roots,
    running: isGameRunning(),
    cfgName: CFG_NAME,
    execName: EXEC_NAME,
    execLine: execLine(),
  };
}

